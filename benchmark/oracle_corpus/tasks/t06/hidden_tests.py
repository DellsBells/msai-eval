import solution


def test_fully_nested_valid():
    assert solution.check_brackets("([{}])") == (True, 3, -1)


def test_valid_with_noise():
    assert solution.check_brackets("a(b)c[d]e") == (True, 1, -1)


def test_empty_string():
    assert solution.check_brackets("") == (True, 0, -1)


def test_no_brackets_at_all():
    assert solution.check_brackets("hello world 123") == (True, 0, -1)


def test_lone_closing():
    assert solution.check_brackets(")") == (False, 0, 0)
    assert solution.check_brackets("a)b") == (False, 0, 1)


def test_mismatched_close():
    # ']' at index 2 does not match '(' opened at index 1.
    assert solution.check_brackets("[(])") == (False, 2, 2)


def test_wrong_close_type_after_opens():
    # '(([)' -> three openers push depth to 3, then ')' at index 3 mismatches
    # the '[' at index 2.
    assert solution.check_brackets("(([)") == (False, 3, 3)


def test_unclosed_single():
    # '({}' climbs to depth 2, closes '}', leaves '(' (index 0) unclosed.
    assert solution.check_brackets("({}") == (False, 2, 0)


def test_unclosed_reports_leftmost():
    # Both '(' (index 3) and '[' (index 7) remain unclosed; report the first.
    assert solution.check_brackets("foo(bar[") == (False, 2, 3)


def test_unclosed_trailing_open():
    assert solution.check_brackets("foo(bar") == (False, 1, 3)


def test_depth_flat_sequence():
    # Three separate shallow groups: max depth is 1.
    assert solution.check_brackets("()[]{}") == (True, 1, -1)


def test_early_mismatch_beats_later_unclosed():
    # The mismatch at the ']' is reported, not the never-closed '{'.
    # '{' opens (0), '(' opens (1), then ']' at 2 mismatches '('.
    assert solution.check_brackets("{(]") == (False, 2, 2)


def test_stray_close_after_pop_keeps_max_depth():
    # '(' opens (depth 1, max 1), ')' closes (depth back to 0), then the ')'
    # at index 2 is a stray close. The reported depth must be the MAXIMUM
    # ever reached (1), NOT the current depth at the error (0).
    assert solution.check_brackets("())") == (False, 1, 2)


def test_stray_close_after_deeper_pop_keeps_max_depth():
    # '((' pushes depth to 2, then '))' pops back to 0, then the final ')'
    # at index 4 is stray. Max depth reached was 2, current depth is 0.
    assert solution.check_brackets("(()))") == (False, 2, 4)


def test_mixed_group_then_stray_close_keeps_max_depth():
    # '([' -> depth 2, '])' close both -> depth 0, then ']' at index 4 is a
    # stray close. Reported depth is the peak (2), not the depth at the error.
    assert solution.check_brackets("([])]") == (False, 2, 4)


def test_mismatch_after_pop_keeps_max_depth():
    # '(' opens (max 1), ')' closes (depth 0), '[' opens (max still 1 vs new 1),
    # then '}' at index 3 mismatches the '['. Error is a mismatch (rule 2) at a
    # point where an earlier group was already closed. Max depth is 1.
    # Walk: ( ->1, ) ->0, [ ->1, } mismatches '[' at index 3.
    assert solution.check_brackets("()[}") == (False, 1, 3)


def test_mismatch_after_peak_unwound_keeps_max_depth():
    # Rule-2 mismatch that occurs AFTER the peak depth was reached and partially
    # unwound. The reported depth must be the maximum ever reached, NOT the
    # running depth at the mismatched close.
    # '(())( ]': ( ->1, ( ->2 (peak), ) ->1, ) ->0, ( ->1, then ']' at index 6
    # mismatches the '(' opened at index 5. Running depth there is 1, peak is 2.
    assert solution.check_brackets("(())( ]") == (False, 2, 6)
    # '((()))(]': depth climbs to 3 (peak), unwinds to 0, '(' ->1, then ']' at
    # index 7 mismatches '('. Running depth 1, peak 3.
    assert solution.check_brackets("((()))(]") == (False, 3, 7)
    # '(())(]': ( ->1, ( ->2 (peak), ) ->1, ) ->0, ( ->1, ']' at index 5 mismatches
    # the '(' at index 4. Peak 2, running depth 1.
    assert solution.check_brackets("(())(]") == (False, 2, 5)
    # '[[]](]': [ ->1, [ ->2 (peak), ] ->1, ] ->0, ( ->1, ')' expected but ']' at
    # index 5 mismatches '('. Peak 2, running depth 1.
    assert solution.check_brackets("[[]](]") == (False, 2, 5)


def test_stray_close_after_noise_and_pop():
    # Non-bracket chars interleaved. 'a(b)c)' -> '(' (max 1), ')' closes,
    # then ')' at index 5 is stray with an empty stack. Depth is peak 1.
    assert solution.check_brackets("a(b)c)") == (False, 1, 5)


def test_deep_nesting_depth_value():
    s = "(" * 10 + ")" * 10
    assert solution.check_brackets(s) == (True, 10, -1)


def test_property_balanced_generation():
    # Property: strings generated by a correct grammar are always balanced,
    # ok is True, position is -1, and depth equals the true maximum nesting.
    import random

    rng = random.Random(99)
    openers = "([{"
    closer = {"(": ")", "[": "]", "{": "}"}

    def gen(max_depth_budget):
        # Returns (string, actual_max_depth) for a balanced sequence.
        if max_depth_budget <= 0 or rng.random() < 0.35:
            return ("", 0)
        parts = []
        best = 0
        n = rng.randint(1, 3)
        for _ in range(n):
            op = rng.choice(openers)
            inner, inner_depth = gen(max_depth_budget - 1)
            parts.append(op + inner + closer[op])
            best = max(best, 1 + inner_depth)
        return ("".join(parts), best)

    for _ in range(300):
        s, true_depth = gen(rng.randint(0, 5))
        ok, depth, pos = solution.check_brackets(s)
        assert ok is True
        assert pos == -1
        assert depth == true_depth


def _true_max_depth(text):
    # Independent reference for the maximum nesting depth reached over a
    # (possibly invalid) prefix, stopping at the first structural error.
    pairs = {")": "(", "]": "[", "}": "{"}
    opens = set("([{")
    closes = set(")]}")
    stack = []
    best = 0
    for ch in text:
        if ch in opens:
            stack.append(ch)
            if len(stack) > best:
                best = len(stack)
        elif ch in closes:
            if not stack or stack[-1] != pairs[ch]:
                break
            stack.pop()
    return best


def _gen_balanced(rng, budget):
    # Build a balanced bracket string with guaranteed nesting and return
    # (string, true_max_depth). Non-bracket noise is sprinkled in freely.
    openers = "([{"
    closer = {"(": ")", "[": "]", "{": "}"}
    noise = "xy z"

    def sprinkle():
        return "".join(rng.choice(noise) for _ in range(rng.randint(0, 2)))

    def build(b):
        if b <= 0 or rng.random() < 0.3:
            return (sprinkle(), 0)
        parts = []
        best = 0
        for _ in range(rng.randint(1, 3)):
            op = rng.choice(openers)
            inner, inner_depth = build(b - 1)
            parts.append(sprinkle() + op + inner + closer[op] + sprinkle())
            best = max(best, 1 + inner_depth)
        return ("".join(parts), best)

    return build(budget)


def test_property_unbalanced_extra_close():
    # Property: appending an unmatched closer to a balanced string makes it
    # invalid, the error is at the appended closer's index, and the reported
    # depth is the MAXIMUM nesting reached (equal to the base's max depth),
    # not the current depth at the stray closer (which is 0 there because the
    # base is fully balanced and closed).
    import random

    rng = random.Random(7)
    checked_nonzero_depth = 0
    for _ in range(100):
        # Force a nonzero budget most of the time so bases actually nest.
        base, true_depth = _gen_balanced(rng, rng.randint(1, 4))
        ok0, d0, p0 = solution.check_brackets(base)
        # The generator only produces balanced strings.
        assert ok0 is True
        assert p0 == -1
        assert d0 == true_depth
        broken = base + ")"
        ok, depth, pos = solution.check_brackets(broken)
        assert ok is False
        assert pos == len(base)
        # At the stray closer the running depth is 0, but the max ever reached
        # equals the base's peak nesting. This distinguishes reporting the
        # maximum depth from reporting the current depth.
        expected_depth = _true_max_depth(base)
        assert depth == expected_depth == true_depth
        if expected_depth > 0:
            checked_nonzero_depth += 1
    # Guarantee the max-vs-current distinction was actually exercised many
    # times: a solution that reports current depth would return 0 here.
    assert checked_nonzero_depth >= 30


def test_property_mismatch_after_peak_keeps_max_depth():
    # Property: for a fully-balanced base (peak nesting = true_depth), append a
    # single opener followed by a NON-matching closer. This is a rule-2 mismatch
    # whose running depth at the error is exactly 1, while the maximum ever
    # reached is max(true_depth, 1). A solution that reports the current depth on
    # the mismatch path would return 1 here instead of the peak, so this pins the
    # 'report the peak, not the depth at the error' rule for rule-2 mismatches.
    import random

    rng = random.Random(4242)
    closer = {"(": ")", "[": "]", "{": "}"}
    wrong = {"(": "]", "[": "}", "{": ")"}
    checked_peak_gt_one = 0
    for _ in range(200):
        base, true_depth = _gen_balanced(rng, rng.randint(1, 4))
        # Sanity: the base is balanced on its own.
        assert solution.check_brackets(base) == (True, true_depth, -1)
        op = rng.choice("([{")
        # base + one opener + a closer that does NOT match that opener.
        broken = base + op + wrong[op]
        mismatch_index = len(base) + 1
        expected_depth = max(true_depth, 1)
        ok, depth, pos = solution.check_brackets(broken)
        assert ok is False
        # Rule 2 fires at the mismatched closer, before any unclosed-open check.
        assert pos == mismatch_index
        # Reported depth is the PEAK, not the running depth (which is 1 here).
        assert depth == expected_depth
        if expected_depth > 1:
            checked_peak_gt_one += 1
    # Ensure many cases had a peak strictly greater than the running depth (1)
    # at the mismatch, so current-depth reporters are actually distinguished.
    assert checked_peak_gt_one >= 30
